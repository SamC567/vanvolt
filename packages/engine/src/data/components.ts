const ACCESSED = '2026-11-07';

function victron(title: string, url: string, note?: string): SourceRef {
  return {
    title,
    url,
    publisher: 'Victron Energy',
    accessed: ACCESSED,
    verification: 'document',
    ...(note ? { note } : {}),
  };
}

