/**
 * Appliance presets.
 *
 * `manufacturer` presets take their power figure from the cited manufacturer source.
 * Usage (hours, days, profile) is only a starting point — the user should edit it.
 * `estimate` presets are generic placeholders, not product specifications: replace
 * their wattage with the rating on your own appliance.
 */
import type { Appliance, SourceRef } from '../types';

export type AppliancePreset = Omit<Appliance, 'id' | 'enabled' | 'libraryId'> & {
  presetId: string;
};

const ACCESSED = '2026-11-07';
const src = (
  title: string,
  url: string,
  publisher: string,
  note?: string,
  verification: 'document' | 'secondary' = 'document',
): SourceRef => ({
  title,
  url,
  publisher,
  accessed: ACCESSED,
  verification,
  ...(note ? { note } : {}),
});

